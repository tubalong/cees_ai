INSERT INTO "role_permissions" ("id", "tenant_id", "role_id", "permission_id", "created_at")
SELECT
    md5(role."id"::text || permission."id"::text)::uuid,
    role."tenant_id",
    role."id",
    permission."id",
    CURRENT_TIMESTAMP
FROM "roles" role
JOIN "permissions" permission ON permission."code" IN (
    'department.read',
    'department.create',
    'department.update',
    'department.delete',
    'department.member.assign'
)
WHERE role."code" = 'tenant_admin' AND role."deleted_at" IS NULL
ON CONFLICT ("tenant_id", "role_id", "permission_id") DO NOTHING;

