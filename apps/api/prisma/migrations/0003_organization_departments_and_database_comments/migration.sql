-- Add the tenant department hierarchy and management metadata.
CREATE TYPE "DepartmentStatus" AS ENUM ('ACTIVE', 'DISABLED');

ALTER TABLE "departments"
    ADD COLUMN "normalized_name" TEXT,
    ADD COLUMN "description" TEXT,
    ADD COLUMN "sort_order" INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN "status" "DepartmentStatus" NOT NULL DEFAULT 'ACTIVE';

UPDATE "departments"
SET "normalized_name" = lower(regexp_replace(btrim("name"), '\s+', ' ', 'g'));

ALTER TABLE "departments"
    ALTER COLUMN "normalized_name" SET NOT NULL;

ALTER TABLE "departments"
    ADD CONSTRAINT "departments_parent_id_fkey"
    FOREIGN KEY ("parent_id") REFERENCES "departments"("id")
    ON DELETE RESTRICT ON UPDATE CASCADE;

CREATE INDEX "departments_tenant_id_status_sort_order_idx"
    ON "departments"("tenant_id", "status", "sort_order");

CREATE UNIQUE INDEX "departments_tenant_parent_name_active_key"
    ON "departments"("tenant_id", "parent_id", "normalized_name")
    WHERE "deleted_at" IS NULL AND "parent_id" IS NOT NULL;

CREATE UNIQUE INDEX "departments_tenant_root_name_active_key"
    ON "departments"("tenant_id", "normalized_name")
    WHERE "deleted_at" IS NULL AND "parent_id" IS NULL;

